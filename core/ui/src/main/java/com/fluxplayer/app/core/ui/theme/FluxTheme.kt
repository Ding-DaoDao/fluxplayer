package com.fluxplayer.app.core.ui.theme

import androidx.compose.runtime.Composable
import androidx.compose.runtime.ReadOnlyComposable
import androidx.compose.runtime.compositionLocalOf
import androidx.compose.runtime.staticCompositionLocalOf
import dev.chrisbanes.haze.HazeState

val LocalFluxColorScheme = staticCompositionLocalOf { lightFluxColorScheme() }
val LocalFluxTypography = staticCompositionLocalOf { defaultFluxTypography() }
val LocalHazeState = compositionLocalOf<HazeState?> { null }

object FluxTheme {
    val colorScheme: FluxColorScheme
        @Composable
        @ReadOnlyComposable
        get() = LocalFluxColorScheme.current

    val typography: FluxTypography
        @Composable
        @ReadOnlyComposable
        get() = LocalFluxTypography.current
}

